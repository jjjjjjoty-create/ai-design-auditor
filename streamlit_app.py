            response = client.models.generate_content(
                model="gemini-3.7-flash",
                contents=[
                    prompt,
                    {
                        "inline_data": {
                            "mime_type": uploaded_file.type,
                            "data": image_bytes
                        }
                    }
                ]
            )


            # ==============================
            # ВЫВОД РЕЗУЛЬТАТА
